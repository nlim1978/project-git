    public function __construct()
    {
        parent::__construct();

        // Ensure that we always set the database group to 'tests' if
        // we are currently running an automated test suite, so that
        // we don't overwrite live data on accident.
        if (ENVIRONMENT === 'testing') {
            $this->defaultGroup = 'tests';

            // Local SQL Server installations commonly use a named instance
            // instead of 127.0.0.1:1433. Unless a dedicated test server is
            // explicitly configured, reuse the working default connection
            // details while keeping the separate tests database name.
            if (trim((string) env('database.tests.hostname', '')) === '') {
                $this->tests['hostname'] = $this->default['hostname'];
                $this->tests['username'] = $this->default['username'];
                $this->tests['password'] = $this->default['password'];
                $this->tests['port']     = $this->default['port'];
            }
        }
    }
